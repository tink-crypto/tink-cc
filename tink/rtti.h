#ifndef TINK_RTTI_H_
#define TINK_RTTI_H_

// Run-time and compile-time type identification utilities for Tink C++.
//
// This header provides a portable subset of C++ RTTI in `crypto::tink`:
//
//   * `TypeIndex`: Hashable, comparable value type identifying a C++ type.
//   * `GetStaticTypeIndex<T>()`: Returns the compile-time `TypeIndex` for `T`,
//     ignoring top-level cv-qualifiers and references.
//   * `GetTypeIndex(const T& object)`: Returns the dynamic `TypeIndex` of
//     `object`'s runtime type (pass a reference, e.g. `*ptr`, not a pointer).
//   * `DynamicCast<To>(From* from)`: Safely downcasts pointer `from` to pointer
//     type `To` (e.g., `const Key*` to `const HmacKey*`), returning `nullptr`
//     if `from == nullptr` or if `from` is not an instance of `To`.
//
// Build modes:
//   * Default mode (`TINK_USE_CUSTOM_RTTI` undefined):
//     Backed directly by standard C++ RTTI (`std::type_index`, `typeid`, and
//     `dynamic_cast`). Internal `TINK_INTERNAL_RTTI_*` class macros expand to
//     nothing and add zero vtable or object-size overhead.
//   * Custom RTTI mode (`TINK_USE_CUSTOM_RTTI` defined):
//     Backed by explicit 64-bit integer type IDs and virtual dispatch methods
//     generated by Tink's internal `TINK_INTERNAL_RTTI_*` macros, allowing Tink
//     to compile and run with `-fno-rtti`. In this mode, only Tink types
//     carrying `TINK_INTERNAL_RTTI_*` annotations are supported (`DynamicCast`
//     supports non-virtual pointer downcasts only).
//
// Usage example:
//
//   crypto::tink::TypeIndex static_idx =
//       crypto::tink::GetStaticTypeIndex<HmacParameters>();
//   crypto::tink::TypeIndex dynamic_idx =
//       crypto::tink::GetTypeIndex(params_ref);
//   const auto* hmac =
//       crypto::tink::DynamicCast<const HmacParameters*>(params_ptr);

// IWYU pragma: begin_exports
#if defined(TINK_USE_CUSTOM_RTTI)
#include "tink/internal/rtti_manual.h"
#else
#include "tink/internal/rtti_native.h"
#endif
// IWYU pragma: end_exports

#endif  // TINK_RTTI_H_
