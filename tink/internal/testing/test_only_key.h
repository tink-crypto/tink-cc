// Test-only key types, for tests of Tink features that do not depend on a
// specific algorithm (keyset handles, configurations, registries, keyset
// wrappers...). They provide no security at all: their primitives are the
// dummy primitives of `util/test_util.h`.
//
// The keys reuse the test-only protos of `proto/test_proto.proto`:
//   * symmetric keys: `TestProtoWithoutCtype`, with `str` = key material;
//   * key formats: `TestProto`, with `num` = key size in bytes.

inline constexpr absl::string_view kTestOnlyKeyTypeUrl =
    "type.googleapis.com/google.crypto.tink.TestProtoWithoutCtype";

// Size of the key material of the keys generated by this library.
inline constexpr int kTestOnlyKeySizeInBytes = 16;

// Parameters of a `TestOnlySymmetricKey`.
class TestOnlyParameters final : public Parameters {
 public:
  // Output prefix of the key.
  enum class Variant : int {
    // Prefix '0x01<big endian key id>'.
    kTink = 1,
    // Prefix '0x00<big endian key id>'.
    kCrunchy = 2,
    // Prefix '0x00<big endian key id>'.
    kLegacy = 3,
    // No prefix (i.e., keys must have no ID requirement).
    kNoPrefix = 4,
    // Added to guard from failures that may be caused by future expansions.
    kDoNotUseInsteadUseDefaultWhenWritingSwitchStatements = 20,
  };

  // Copyable and movable.
  TestOnlyParameters(const TestOnlyParameters& other) = default;
  TestOnlyParameters& operator=(const TestOnlyParameters& other) = default;
  TestOnlyParameters(TestOnlyParameters&& other) = default;
  TestOnlyParameters& operator=(TestOnlyParameters&& other) = default;

  // Returns an error if `variant` is invalid.
  static absl::StatusOr<TestOnlyParameters> Create(Variant variant);

  Variant GetVariant() const { return variant_; }

  bool HasIdRequirement() const override {
    return variant_ != Variant::kNoPrefix;
  }

  bool operator==(const Parameters& other) const override;

  std::unique_ptr<Parameters> Clone() const override {
    return std::make_unique<TestOnlyParameters>(*this);
  }

 private:
  explicit TestOnlyParameters(Variant variant) : variant_(variant) {}

  Variant variant_;
};

// A test-only symmetric key.
class TestOnlySymmetricKey final : public Key {
 public:
  // Copyable and movable.
  TestOnlySymmetricKey(const TestOnlySymmetricKey& other) = default;
  TestOnlySymmetricKey& operator=(const TestOnlySymmetricKey& other) = default;
  TestOnlySymmetricKey(TestOnlySymmetricKey&& other) = default;
  TestOnlySymmetricKey& operator=(TestOnlySymmetricKey&& other) = default;

  // Returns an error if `id_requirement` doesn't match
  // `parameters.HasIdRequirement()`. `key_bytes` can have any size.
  static absl::StatusOr<TestOnlySymmetricKey> Create(
      const TestOnlyParameters& parameters, const RestrictedData& key_bytes,
      absl::optional<int> id_requirement, PartialKeyAccessToken token);

  const RestrictedData& GetKeyBytes(PartialKeyAccessToken token) const {
    return key_bytes_;
  }

  absl::string_view GetOutputPrefix() const { return output_prefix_; }

  const TestOnlyParameters& GetParameters() const override {
    return parameters_;
  }

  absl::optional<int32_t> GetIdRequirement() const override {
    return id_requirement_;
  }

  bool operator==(const Key& other) const override;

  std::unique_ptr<Key> Clone() const override {
    return std::make_unique<TestOnlySymmetricKey>(*this);
  }

 private:
  TestOnlySymmetricKey(const TestOnlyParameters& parameters,
                       const RestrictedData& key_bytes,
                       absl::optional<int> id_requirement,
                       std::string output_prefix)
      : parameters_(parameters),
        key_bytes_(key_bytes),
        id_requirement_(id_requirement),
        output_prefix_(std::move(output_prefix)) {}

  TestOnlyParameters parameters_;
  RestrictedData key_bytes_;
  absl::optional<int> id_requirement_;
  std::string output_prefix_;
};

// Registers the proto serialization of `TestOnlyParameters` and
// `TestOnlySymmetricKey` (with type URL `kTestOnlyKeyTypeUrl`) in the global
// `MutableSerializationRegistry`.
absl::Status RegisterTestOnlyProtoSerialization();

// Creates a `TestOnlySymmetricKey` with random key material of
// `kTestOnlyKeySizeInBytes` bytes. Can be added to a `KeyGenConfiguration`
// with `KeyGenConfigurationImpl::AddKeyCreator<TestOnlyParameters>`.
absl::StatusOr<std::unique_ptr<Key>> CreateTestOnlyKey(
    const TestOnlyParameters& parameters, absl::optional<int> id_requirement);

// Returns a `test::DummyAead` for `key`. Can be added to a `Configuration`
// with `ConfigurationImpl::AddPrimitiveGetter<Aead, TestOnlySymmetricKey>`.
absl::StatusOr<std::unique_ptr<Aead>> NewTestOnlyAead(
    const TestOnlySymmetricKey& key);

