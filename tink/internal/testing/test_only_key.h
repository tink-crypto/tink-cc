#ifndef TINK_INTERNAL_TESTING_TEST_ONLY_KEY_H_
#define TINK_INTERNAL_TESTING_TEST_ONLY_KEY_H_

#include <memory>

#include "absl/status/status.h"
#include "absl/status/statusor.h"
#include "absl/strings/string_view.h"
#include "tink/parameters.h"

namespace crypto {
namespace tink {
namespace internal {

// Test-only key types, for tests of Tink features that do not depend on a
// specific algorithm (keyset handles, configurations, registries, keyset
// wrappers...). They provide no security at all.
//
// The keys reuse the test-only protos of `proto/test_proto.proto`:
//   * symmetric keys: `TestProtoWithoutCtype`, with `str` = key material;
//   * key formats: `TestProto`, with `num` = key size in bytes.

inline constexpr absl::string_view kTestOnlyKeyTypeUrl =
    "type.googleapis.com/google.crypto.tink.TestProtoWithoutCtype";

// Size of the key material of the keys generated by this library.
inline constexpr int kTestOnlyKeySizeInBytes = 16;

// Parameters of a `TestOnlyKey`.
class TestOnlyParameters final : public Parameters {
 public:
  // Output prefix of the key.
  enum class Variant : int {
    // Prefix '0x01<big endian key id>'.
    kTink = 1,
    // Prefix '0x00<big endian key id>'.
    kCrunchy = 2,
    // Prefix '0x00<big endian key id>'.
    kLegacy = 3,
    // No prefix (i.e., keys must have no ID requirement).
    kNoPrefix = 4,
    // Added to guard from failures that may be caused by future expansions.
    kDoNotUseInsteadUseDefaultWhenWritingSwitchStatements = 20,
  };

  // Copyable and movable.
  TestOnlyParameters(const TestOnlyParameters& other) = default;
  TestOnlyParameters& operator=(const TestOnlyParameters& other) = default;
  TestOnlyParameters(TestOnlyParameters&& other) = default;
  TestOnlyParameters& operator=(TestOnlyParameters&& other) = default;

  // Returns an error if `variant` is invalid.
  static absl::StatusOr<TestOnlyParameters> Create(Variant variant);

  Variant GetVariant() const { return variant_; }

  bool HasIdRequirement() const override {
    return variant_ != Variant::kNoPrefix;
  }

  bool operator==(const Parameters& other) const override;

  std::unique_ptr<Parameters> Clone() const override {
    return std::make_unique<TestOnlyParameters>(*this);
  }

 private:
  explicit TestOnlyParameters(Variant variant) : variant_(variant) {}

  Variant variant_;
};

// Registers the proto serialization of `TestOnlyParameters` (with type URL
// `kTestOnlyKeyTypeUrl`) in the global `MutableSerializationRegistry`.
absl::Status RegisterTestOnlyProtoSerialization();

}  // namespace internal
}  // namespace tink
}  // namespace crypto

#endif  // TINK_INTERNAL_TESTING_TEST_ONLY_KEY_H_
