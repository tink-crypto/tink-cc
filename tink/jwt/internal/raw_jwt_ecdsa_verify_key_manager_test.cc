const internal::SignatureTestVector& GetTestVector(
    EcdsaParameters::CurveType curve_type,
    EcdsaParameters::HashType hash_type) {
  return internal::GetEcdsaTestVector(
      curve_type, hash_type, EcdsaParameters::SignatureEncoding::kIeeeP1363,
      EcdsaParameters::Variant::kNoPrefix);
}

const EcdsaPrivateKey& GetTestVectorPrivateKey(
    EcdsaParameters::CurveType curve_type,
    EcdsaParameters::HashType hash_type) {
  const internal::SignatureTestVector& test_vector =
      GetTestVector(curve_type, hash_type);
  const auto* private_key = dynamic_cast<const EcdsaPrivateKey*>(
      test_vector.signature_private_key.get());
  ABSL_CHECK_NE(private_key, nullptr);
  return *private_key;
}

JwtEcdsaPublicKey ToJwtEcdsaPublicKey(const EcdsaPublicKey& public_key,
                                      JwtEcdsaAlgorithm algorithm) {
  JwtEcdsaPublicKey proto;
  proto.set_version(0);
  proto.set_algorithm(algorithm);
  proto.set_x(std::string(
      public_key.GetPublicPoint(GetPartialKeyAccess()).GetX().GetValue()));
  proto.set_y(std::string(
      public_key.GetPublicPoint(GetPartialKeyAccess()).GetY().GetValue()));
  return proto;
}

JwtEcdsaPrivateKey ToJwtEcdsaPrivateKey(const EcdsaPrivateKey& private_key,
                                        JwtEcdsaAlgorithm algorithm) {
  JwtEcdsaPrivateKey key;
  key.set_version(0);
  key.set_key_value(private_key.GetPrivateKey(GetPartialKeyAccess())
                        .GetSecret(InsecureSecretKeyAccess::Get()));
  *key.mutable_public_key() =
      ToJwtEcdsaPublicKey(private_key.GetPublicKey(), algorithm);
  return key;
}

TEST(RawJwtEcdsaVerifyKeyManagerTest, Basics) {
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().get_version(), Eq(0));
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().key_material_type(),
              Eq(KeyData::ASYMMETRIC_PUBLIC));
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().get_key_type(),
              Eq("type.googleapis.com/google.crypto.tink.JwtEcdsaPublicKey"));
}

TEST(RawJwtEcdsaVerifyKeyManagerTest, ValidateEmptyKey) {
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().ValidateKey(JwtEcdsaPublicKey()),
              Not(IsOk()));
}

JwtEcdsaPrivateKey CreateValidEs256PrivateKey() {
  return ToJwtEcdsaPrivateKey(
      GetTestVectorPrivateKey(EcdsaParameters::CurveType::kNistP256,
                              EcdsaParameters::HashType::kSha256),
      JwtEcdsaAlgorithm::ES256);
}

// Checks that a public key generated by the SignKeyManager is considered valid.
TEST(RawJwtEcdsaVerifyKeyManagerTest, PublicKeyValid) {
  absl::StatusOr<JwtEcdsaPublicKey> key =
      RawJwtEcdsaSignKeyManager().GetPublicKey(CreateValidEs256PrivateKey());
  ASSERT_THAT(key, IsOk());
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().ValidateKey(*key), IsOk());
}

TEST(EcdsaSignKeyManagerTest, ValidateKeyUnknownAlgorithm) {
  absl::StatusOr<JwtEcdsaPublicKey> key =
      RawJwtEcdsaSignKeyManager().GetPublicKey(CreateValidEs256PrivateKey());
  ASSERT_THAT(key, IsOk());
  key->set_algorithm(JwtEcdsaAlgorithm::ES_UNKNOWN);
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().ValidateKey(*key), Not(IsOk()));
  EXPECT_THAT(RawJwtEcdsaVerifyKeyManager().ValidateKey(*key),
              StatusIs(absl::StatusCode::kInvalidArgument));
}

TEST(EcdsaSignKeyManagerTest, Create) {
  const EcdsaPrivateKey& ecdsa_private_key =
      GetTestVectorPrivateKey(EcdsaParameters::CurveType::kNistP256,
                              EcdsaParameters::HashType::kSha256);
  JwtEcdsaPublicKey public_key = ToJwtEcdsaPublicKey(
      ecdsa_private_key.GetPublicKey(), JwtEcdsaAlgorithm::ES256);

  absl::StatusOr<std::unique_ptr<subtle::EcdsaSignBoringSsl>> direct_signer =
      subtle::EcdsaSignBoringSsl::New(ecdsa_private_key);
  ASSERT_THAT(direct_signer, IsOk());

  absl::StatusOr<std::unique_ptr<PublicKeyVerify>> verifier =
      RawJwtEcdsaVerifyKeyManager().GetPrimitive<PublicKeyVerify>(public_key);
  ASSERT_THAT(verifier, IsOk());

  std::string message = "Some message";
  absl::StatusOr<std::string> sig = (*direct_signer)->Sign(message);
  ASSERT_THAT(sig, IsOk());
  EXPECT_THAT((*verifier)->Verify(*sig, message), IsOk());
}

TEST(EcdsaSignKeyManagerTest, CreateDifferentPrivateKey) {
  const EcdsaPrivateKey& ecdsa_private_key =
      GetTestVectorPrivateKey(EcdsaParameters::CurveType::kNistP256,
                              EcdsaParameters::HashType::kSha256);
  const EcdsaPrivateKey& different_ecdsa_private_key =
      GetTestVectorPrivateKey(EcdsaParameters::CurveType::kNistP384,
                              EcdsaParameters::HashType::kSha384);

  absl::StatusOr<std::unique_ptr<subtle::EcdsaSignBoringSsl>> direct_signer =
      subtle::EcdsaSignBoringSsl::New(ecdsa_private_key);
  ASSERT_THAT(direct_signer, IsOk());

  JwtEcdsaPublicKey different_public_key = ToJwtEcdsaPublicKey(
      different_ecdsa_private_key.GetPublicKey(), JwtEcdsaAlgorithm::ES384);
  absl::StatusOr<std::unique_ptr<PublicKeyVerify>> verifier =
      RawJwtEcdsaVerifyKeyManager().GetPrimitive<PublicKeyVerify>(
          different_public_key);
  ASSERT_THAT(verifier, IsOk());

  std::string message = "Some message";
  absl::StatusOr<std::string> sig = (*direct_signer)->Sign(message);
  ASSERT_THAT(sig, IsOk());
  EXPECT_THAT((*verifier)->Verify(*sig, message), Not(IsOk()));
}

struct TestVectorCase {
  JwtEcdsaAlgorithm algorithm;
  EcdsaParameters::CurveType curve_type;
  EcdsaParameters::HashType hash_type;
};

using RawJwtEcdsaVerifyKeyManagerTestVectorTest =
    testing::TestWithParam<TestVectorCase>;

TEST_P(RawJwtEcdsaVerifyKeyManagerTestVectorTest, VerifyTestVectorSignature) {
  const TestVectorCase& test_case = GetParam();
  const internal::SignatureTestVector& test_vector =
      GetTestVector(test_case.curve_type, test_case.hash_type);
  const EcdsaPrivateKey& ecdsa_private_key =
      GetTestVectorPrivateKey(test_case.curve_type, test_case.hash_type);
  JwtEcdsaPublicKey public_key = ToJwtEcdsaPublicKey(
      ecdsa_private_key.GetPublicKey(), test_case.algorithm);

  absl::StatusOr<std::unique_ptr<PublicKeyVerify>> verifier =
      RawJwtEcdsaVerifyKeyManager().GetPrimitive<PublicKeyVerify>(public_key);
  ASSERT_THAT(verifier, IsOk());
  EXPECT_THAT((*verifier)->Verify(test_vector.signature, test_vector.message),
              IsOk());
  EXPECT_THAT((*verifier)->Verify(test_vector.signature, "wrong message"),
              Not(IsOk()));
}

INSTANTIATE_TEST_SUITE_P(
    RawJwtEcdsaVerifyKeyManagerTestVectorTests,
    RawJwtEcdsaVerifyKeyManagerTestVectorTest,
    Values(TestVectorCase{JwtEcdsaAlgorithm::ES256,
                          EcdsaParameters::CurveType::kNistP256,
                          EcdsaParameters::HashType::kSha256},
           TestVectorCase{JwtEcdsaAlgorithm::ES384,
                          EcdsaParameters::CurveType::kNistP384,
                          EcdsaParameters::HashType::kSha384},
           TestVectorCase{JwtEcdsaAlgorithm::ES512,
                          EcdsaParameters::CurveType::kNistP521,
                          EcdsaParameters::HashType::kSha512}));

